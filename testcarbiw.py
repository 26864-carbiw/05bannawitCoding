print("โปรเเกรมตรวจสอบความเร็วรถ\n")
speed = int(input("โปรดกรอกความเร็วรถkm/h : "))

if speed >= 120:
    print("ผิดกฏหมาย ปรับทันที")

elif speed >= 101:
    print("เสี่ยงถูกปรับ")

elif speed >= 81:
    print("เตือนไม่ควรขับเร็ว")

else:
    print("ปลอดภัย")

